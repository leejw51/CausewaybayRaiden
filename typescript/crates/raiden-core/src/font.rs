//! The 5x7 arcade font from `src/gfx.lua`, in 8x8 cells.
//!
//! The rows are kept as art rather than as hex so a glyph can be read and
//! edited in place. Packing to one byte per row happens once, and the packed
//! form is handed to the browser so it can bake a font atlas: every string in
//! the game then costs one draw call per character instead of one per lit
//! pixel, which is what LÖVE was doing.
//!
//! Width is fixed at 8 pixels per character, so `text_width` is exact and the
//! menus can centre themselves without asking the renderer anything.

