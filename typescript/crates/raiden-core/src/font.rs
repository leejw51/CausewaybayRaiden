/// Eight bytes per glyph, in `CHARSET` order. Bit 7 is the leftmost pixel.
pub fn bitmap() -> &'static [u8] {
    static PACKED: OnceLock<Vec<u8>> = OnceLock::new();
    PACKED.get_or_init(|| {
        let mut out = Vec::with_capacity(ROWS.len() * 8);
        for glyph in ROWS {
            for row in glyph {
                let mut bits = 0u8;
                for (c, ch) in row.bytes().take(8).enumerate() {
                    if ch == b'#' {
                        bits |= 1 << (7 - c);
                    }
                }
                out.push(bits);
            }
        }
        out
    })
}

/// Width in pixels of `s` drawn at `scale`. Fixed cell, so it is just a count.
pub fn text_width(s: &str, scale: f32) -> f32 {
    s.chars().count() as f32 * 8.0 * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_charset_entry_has_a_glyph() {
        assert_eq!(CHARSET.chars().count(), ROWS.len());
    }

    #[test]
    fn packing_is_eight_bytes_per_glyph() {
        assert_eq!(bitmap().len(), ROWS.len() * 8);
    }

    #[test]
    fn space_is_blank_and_letters_are_not() {
        let idx = |c: char| CHARSET.find(c).unwrap();
        let bm = bitmap();
        let space = &bm[idx(' ') * 8..idx(' ') * 8 + 8];
        assert!(space.iter().all(|&b| b == 0));
        let a_glyph = &bm[idx('A') * 8..idx('A') * 8 + 8];
        assert!(a_glyph.iter().any(|&b| b != 0));
    }

    #[test]
    fn bit_seven_is_the_leftmost_pixel() {
        // 'L' is a full-height stem in column 0 with a foot along the bottom.
        let i = CHARSET.find('L').unwrap() * 8;
        let bm = bitmap();
        assert_eq!(bm[i] & 0b1000_0000, 0b1000_0000, "stem missing on row 0");
        assert_eq!(bm[i + 6], 0b1111_1100, "foot wrong on row 6");
    }

    #[test]
    fn width_counts_characters_not_bytes() {
        assert_eq!(text_width("RAIDEN", 1.0), 48.0);
        assert_eq!(text_width("RAIDEN", 2.0), 96.0);
        assert_eq!(text_width("", 1.0), 0.0);
    }
}
